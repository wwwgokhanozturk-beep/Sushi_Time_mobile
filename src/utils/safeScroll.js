// Программная прокрутка списков (`scrollToIndex` / `scrollToLocation`) — самый
// частый источник фатального падения в проде: VirtualizedList бросает
// Invariant-ошибку, если индекс вышел за пределы данных или список ещё не
// успел пересчитать кадры после смены `data`.
//
// Именно это происходит при переключении языка: все подписи категорий
// становятся новыми, массив данных пересоздаётся, а эффекты рейла и
// скролл-шпион в тот же тик просят список прокрутиться к позиции, которой в
// его внутреннем состоянии ещё нет. В release-сборке исключение из эффекта или
// из setInterval некому поймать — Android просто закрывает приложение.
//
// Отказ прокрутки — не ошибка: следующий тик скролла всё равно поставит
// активную категорию на место.

/**
 * Выполняет прокрутку в следующем кадре и глушит отказ.
 * @param {() => void} scroll  вызов scrollToIndex/scrollToLocation
 * @returns {() => void} отмена — для cleanup эффекта
 */
export function deferSafeScroll(scroll) {
  const id = requestAnimationFrame(() => {
    try {
      scroll();
    } catch (_) { /* список ещё не готов — позиция догонит следующим тиком */ }
  });
  return () => cancelAnimationFrame(id);
}

/** Синхронный вариант для обработчиков нажатия. */
export function safeScroll(scroll) {
  try {
    scroll();
  } catch (_) { /* см. deferSafeScroll */ }
}
